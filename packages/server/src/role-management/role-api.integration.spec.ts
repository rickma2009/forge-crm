import cookieParser from 'cookie-parser';
import { Test } from '@nestjs/testing';
import type { INestApplication } from '@nestjs/common';
import request from 'supertest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { Pool } from 'pg';
import { hash } from 'argon2';
import { randomBytes } from 'node:crypto';
import { DatabaseService } from '../database/database.service';
import { ApiExceptionFilter } from '../http/api-exception.filter';
import { SessionSigner } from '../auth/session-signer';

const run = process.env.RUN_ROLE_DB_TESTS === '1' ? describe : describe.skip;
run('015 isolated database role API', () => {
  let app: INestApplication;
  let db: DatabaseService;
  let cookie: string;
  let readonlyCookie: string;
  const base = '/api/systems/demo-portal';
  const suffix = Date.now().toString(36);
  let roleId: string;
  let childId: string;
  let userId: string;
  let adminId: string;
  const write = (method: 'post' | 'patch' | 'put' | 'delete', path: string, body: Record<string, unknown>, session = cookie) => request(app.getHttpServer())[method](base + path).set('Cookie', session).set('Origin', 'http://localhost:5173').set('X-CSRF-Token', 'role015-test').send(body);
  beforeAll(async () => {
    const url = new URL(process.env.DATABASE_URL!);
    if (!['127.0.0.1', 'localhost'].includes(url.hostname)) throw new Error('LOCAL_TEST_DATABASE_REQUIRED');
    url.pathname = '/sdd_role_015_20260922_8c72';
    process.env.DATABASE_URL = url.toString();
    const pool = new Pool({ connectionString: url.toString() });
    const column = await pool.query("select 1 from information_schema.columns where table_name='sys_role' and column_name='archived_at'");
    if (!column.rowCount) await pool.query(readFileSync(resolve(process.cwd(), 'prisma/migrations/20260922180000_role_workspace_safety/migration.sql'), 'utf8'));
    const policyTable = await pool.query("select to_regclass('public.sys_role_data_policy') as relation");
    if (!policyTable.rows[0].relation) await pool.query(readFileSync(resolve(process.cwd(), 'prisma/migrations/20260922200000_role_data_policy/migration.sql'), 'utf8'));
    const subjectTable = await pool.query("select to_regclass('public.sys_role_subject_binding') as relation");
    if (!subjectTable.rows[0].relation) await pool.query(readFileSync(resolve(process.cwd(), 'prisma/migrations/20260922210000_role_dynamic_subjects/migration.sql'), 'utf8'));
    // Keep this isolated fixture compatible with the shared user model; never migrate the business database here.
    const employeeTable = await pool.query("select to_regclass('public.org_employee') as relation");
    if (!employeeTable.rows[0].relation) await pool.query(readFileSync(resolve(process.cwd(), 'prisma/migrations/20260922220000_employee_directory/migration.sql'), 'utf8'));
    await pool.end();
    const { AppModule } = await import('../app.module');
    const module = await Test.createTestingModule({ imports: [AppModule] }).compile();
    app = module.createNestApplication(); app.use(cookieParser()); app.useGlobalFilters(new ApiExceptionFilter()); await app.init();
    db = app.get(DatabaseService);
    const admin = await db.iamUser.findFirstOrThrow({ where: { account: 'admin', status: 'ACTIVE' } });
    adminId = admin.id;
    const viewer = await db.iamUser.findFirstOrThrow({ where: { account: 'viewer', status: 'ACTIVE' } });
    const signer = app.get(SessionSigner);
    cookie = `ipl_session=${signer.issue(admin.id)}; ipl_csrf=role015-test`;
    readonlyCookie = `ipl_session=${signer.issue(viewer.id)}; ipl_csrf=role015-test`;
    const user = await db.iamUser.create({ data: { tenantId: admin.tenantId, account: 'role015-' + suffix, normalizedAccount: 'role015-' + suffix, displayName: '角色验证隔离账号', passwordHash: await hash(randomBytes(32)) } });
    userId = user.id;
  }, 30000);
  afterAll(async () => { await app?.close(); });
  it('returns the real resource hierarchy and mapped permissions through the scoped role endpoint', async () => {
    const result = await request(app.getHttpServer()).get(base + '/roles/permission-catalog').set('Cookie', cookie);
    expect(result.status).toBe(200);
    expect(result.body.pages.some((p: { pageType: string }) => p.pageType === 'SYSTEM')).toBe(true);
    const customer = result.body.pages.find((p: { pageCode: string }) => p.pageCode === 'customer-directory');
    expect(customer).toBeDefined(); expect(customer.parentId).toBeTruthy(); expect(customer.permissionIds.length).toBeGreaterThan(0);
    expect(customer.actions.some((a: { permissionIds: string[] }) => a.permissionIds.length > 0)).toBe(true);
    const all = new Set(result.body.permissions.map((p: { id: string }) => p.id));
    expect(customer.permissionIds.every((id: string) => all.has(id))).toBe(true);
    expect((await request(app.getHttpServer()).get(base + '/roles/permission-catalog')).status).toBe(401);
    // The seeded viewer is allowed to inspect roles, but cannot change them.
    expect((await request(app.getHttpServer()).get(base + '/roles/permission-catalog').set('Cookie', readonlyCookie)).status).toBe(200);
    const unassigned = `ipl_session=${app.get(SessionSigner).issue(userId)}`;
    expect((await request(app.getHttpServer()).get(base + '/roles/permission-catalog').set('Cookie', unassigned)).status).toBe(403);
  });
  it('rejects read-only writes, privilege injection, and invalid periods', async () => {
    expect((await write('post', '/roles', { roleCode: 'denied-' + suffix, roleName: '不应创建' }, readonlyCookie)).status).toBe(403);
    expect((await write('post', '/roles', { roleCode: 'denied-' + suffix, roleName: '不应创建', isAdmin: true })).status).toBe(400);
    expect((await write('post', '/roles', { roleCode: 'denied-' + suffix, roleName: '不应创建', effectiveDateBegin: '2026-02-01T00:00:00Z', effectiveDateEnd: '2026-01-01T00:00:00Z' })).status).toBe(400);
  });
  it('creates a scoped tree and rejects cycles, immutable codes and stale versions', async () => {
    const created = await write('post', '/roles', { roleCode: 'test-' + suffix, roleName: '角色验证', isEnabled: true, sortNo: 9000 });
    expect(created.status).toBe(201); roleId = created.body.id;
    const child = await write('post', '/roles', { roleCode: 'child-' + suffix, roleName: '子角色验证', parentId: roleId, isEnabled: true, sortNo: 9000 });
    expect(child.status).toBe(201); childId = child.body.id;
    expect((await write('post', `/roles/${roleId}/move`, { version: 1, targetId: childId, position: 'child' })).status).toBe(409);
    expect((await write('patch', `/roles/${roleId}`, { version: 1, roleCode: 'changed' })).status).toBe(400);
    expect((await write('patch', `/roles/${roleId}`, { version: 1, roleName: '角色验证改名' })).status).toBe(200);
    expect((await write('patch', `/roles/${roleId}`, { version: 1, roleName: '并发覆盖' })).status).toBe(409);
    expect((await write('delete', `/roles/${roleId}`, { version: 2 })).status).toBe(409);
    const tenantId = (await db.iamRole.findUniqueOrThrow({ where: { id: roleId } })).tenantId!;
    const other = await db.sysApplication.create({ data: { tenantId, applicationCode: 'role015-other-' + suffix, applicationName: '隔离作用域测试' } });
    const group = await db.sysRoleGroup.create({ data: { applicationId: other.id, groupCode: 'default', groupName: '测试组' } });
    const otherRole = await db.iamRole.create({ data: { applicationId: other.id, tenantId, roleGroupId: group.id, systemCode: other.applicationCode, roleCode: 'outside', roleName: '不可跨域角色', roleType: 'BUSINESS' } });
    expect((await write('post', `/roles/${roleId}/move`, { version: 2, targetId: otherRole.id, position: 'child' })).status).toBe(400);
  });
  it('uses atomic member batches and immediately revokes disabled role access', async () => {
    const effectiveAt = new Date(Date.now() - 1000).toISOString();
    const permission = await db.sysPermission.findFirstOrThrow({ where: { permissionCode: 'access.role.view', application: { applicationCode: 'demo-portal' } } });
    expect((await write('put', `/access/roles/${roleId}/permissions`, { roleVersion: 2, permissionIds: [permission.id] })).status).toBe(200);
    expect((await write('post', `/access/roles/${roleId}/members/batch`, { action: 'add', userIds: [userId, '10000000-0000-4000-8000-000000000000'], effectiveAt, expiresAt: null })).status).toBe(400);
    expect(await db.iamRoleUser.count({ where: { roleId } })).toBe(0);
    expect((await write('post', `/access/roles/${roleId}/members/batch`, { action: 'add', userIds: [userId], effectiveAt, expiresAt: null })).status).toBe(201);
    expect((await write('post', `/access/roles/${roleId}/members/batch`, { action: 'add', userIds: [userId], effectiveAt, expiresAt: null })).status).toBe(409);
    const userCookie = `ipl_session=${app.get(SessionSigner).issue(userId)}`;
    expect((await request(app.getHttpServer()).get(base + '/roles').set('Cookie', userCookie)).status).toBe(200);
    expect((await write('patch', `/roles/${roleId}`, { version: 3, isEnabled: false })).status).toBe(200);
    expect((await request(app.getHttpServer()).get(base + '/roles').set('Cookie', userCookie)).status).toBe(403);
    expect((await write('patch', `/roles/${roleId}`, { version: 4, isEnabled: true })).status).toBe(200);
    expect((await request(app.getHttpServer()).get(base + '/roles').set('Cookie', userCookie)).status).toBe(200);
  });
  it('assigns existing views, protects system roles and preserves archived history', async () => {
    const views = await request(app.getHttpServer()).get(base + `/roles/${roleId}/views`).set('Cookie', cookie);
    expect(views.status).toBe(200);
    const chosen = views.body.items.find((v: { grantable: boolean }) => v.grantable);
    expect(chosen).toBeDefined();
    expect((await write('post', `/roles/${roleId}/views`, { version: 5, viewIds: [chosen.id] })).status).toBe(201);
    expect(await db.iamRoleListView.count({ where: { roleId, status: 'ACTIVE' } })).toBe(1);
    expect((await write('post', `/roles/${roleId}/views`, { version: 5, viewIds: [] })).status).toBe(409);
    expect((await write('post', `/roles/${roleId}/views`, { version: 6, viewIds: [] })).status).toBe(201);
    const system = await db.iamRole.findFirstOrThrow({ where: { systemCode: 'demo-portal', isSystem: true } });
    expect((await write('patch', `/roles/${system.id}`, { version: system.version, roleName: '不可改' })).status).toBe(409);
    expect((await write('delete', `/roles/${childId}`, { version: 1 })).status).toBe(200);
    expect((await db.iamRole.findUniqueOrThrow({ where: { id: childId } })).archivedAt).not.toBeNull();
    expect((await write('patch', `/access/roles/${childId}/status`, { version: 2, status: 'ACTIVE' })).status).toBe(404);
    expect(await db.sysAuditLog.count({ where: { actorUserId: adminId, resourceId: roleId } })).toBeGreaterThan(0);
  });
  it('enforces published customer data and field rules, rejects concurrent publication and creates rollback history', async () => {
    const permissions = await db.sysPermission.findMany({ where: { application: { applicationCode: 'demo-portal' }, resourceCode: 'customer-directory', status: 'ACTIVE' } });
    const current = await db.iamRole.findUniqueOrThrow({ where: { id: roleId } });
    expect((await write('put', `/access/roles/${roleId}/permissions`, { roleVersion: current.version, permissionIds: permissions.map((p) => p.id) })).status).toBe(200);
    let resource = await db.sysAuthorizationResource.findFirst({ where: { application: { applicationCode: 'demo-portal' }, bindingKey: 'customer' } });
    if (!resource) {
      const registered = await write('post', '/role-policies/catalog', { bindingKey: 'customer', resourceName: '客户数据验证' });
      expect(registered.status).toBe(201);
      resource = registered.body;
    }
    const resourceId = resource!.id;
    const roleVersion = (await db.iamRole.findUniqueOrThrow({ where: { id: roleId } })).version;
    const customer = await db.crmCustomer.findFirstOrThrow({ where: { systemCode: 'demo-portal' } });
    const payload = { version: 0, roleVersion, rules: [{ name: '仅指定客户', enabled: true, effect: 'ALLOW', condition: { kind: 'condition', field: 'id', operator: 'eq', source: 'literal', value: customer.id } }], fields: [{ field: 'address', visible: false, writable: false, exportable: false, mask: 'NONE' }], viewIds: [] };
    const published = await write('post', `/role-policies/${roleId}/${resourceId}/read`, payload);
    expect(published.status).toBe(201);
    if (!resource!.enabled) expect((await write('post', `/role-policies/catalog/${resourceId}/enroll`, { version: resource!.version, enabled: true, confirmDefaultDeny: true })).status).toBe(201);
    const userCookie = `ipl_session=${app.get(SessionSigner).issue(userId)}; ipl_csrf=role015-test`;
    const visible = await request(app.getHttpServer()).get(base + '/customers').set('Cookie', userCookie);
    expect(visible.status).toBe(200);
    expect(visible.body.items.map((c: { id: string }) => c.id)).toEqual([customer.id]);
    expect(visible.body.items[0].address).toBeNull();
    expect(visible.body.pagination.total).toBe(1);
    const outsider = await db.crmCustomer.findFirst({ where: { systemCode: 'demo-portal', id: { not: customer.id } } });
    if (outsider) expect((await request(app.getHttpServer()).get(base + '/customers/' + outsider.id).set('Cookie', userCookie)).status).toBe(404);
    expect((await write('post', `/role-policies/${roleId}/${resourceId}/read`, payload)).status).toBe(409);
    const cleared = await write('post', `/role-policies/${roleId}/${resourceId}/read`, { ...payload, version: 1, roleVersion: published.body.roleVersion, rules: [] });
    expect(cleared.status).toBe(201);
    expect((await request(app.getHttpServer()).get(base + '/customers').set('Cookie', userCookie)).body.pagination.total).toBe(0);
    const rolledBack = await write('post', `/role-policies/${roleId}/${resourceId}/read/rollback/1`, { ...payload, version: 2, roleVersion: cleared.body.roleVersion });
    expect(rolledBack.status).toBe(201);
    expect(rolledBack.body.version).toBe(3);
    expect((await request(app.getHttpServer()).get(base + '/customers').set('Cookie', userCookie)).body.pagination.total).toBe(1);
    const versions = await request(app.getHttpServer()).get(base + `/role-policies/${roleId}/${resourceId}/read`).set('Cookie', cookie);
    expect(versions.body.history.map((h: { version: number }) => h.version)).toEqual([3, 2, 1]);
  });
  it('resolves group grants dynamically and revokes them on the next request after leaving', async () => {
    const userCookie = `ipl_session=${app.get(SessionSigner).issue(userId)}`;
    expect((await request(app.getHttpServer()).get(base + '/roles').set('Cookie', userCookie)).status).toBe(403);
    const group = await write('post', '/role-subjects/groups', { groupCode: 'qa-' + suffix, groupName: '动态授权隔离组' });
    expect(group.status).toBe(201);
    const role = await write('post', '/roles', { roleCode: 'dynamic-' + suffix, roleName: '动态授权验证' });
    expect(role.status).toBe(201);
    const permission = await db.sysPermission.findFirstOrThrow({ where: { permissionCode: 'access.role.view', application: { applicationCode: 'demo-portal' } } });
    expect((await write('put', `/access/roles/${role.body.id}/permissions`, { roleVersion: 1, permissionIds: [permission.id] })).status).toBe(200);
    const period = { effectiveAt: new Date(Date.now() - 1000).toISOString(), expiresAt: null };
    expect((await write('post', `/role-subjects/sources/group/${group.body.id}/members`, { userIds: [userId], ...period })).status).toBe(201);
    expect((await write('post', `/role-subjects/roles/${role.body.id}`, { kind: 'group', subjectIds: [group.body.id], ...period })).status).toBe(201);
    expect((await request(app.getHttpServer()).get(base + '/roles').set('Cookie', userCookie)).status).toBe(200);
    expect(await db.iamRoleUser.count({ where: { roleId: role.body.id, userId } })).toBe(0);
    const members = await request(app.getHttpServer()).get(base + `/role-subjects/sources/group/${group.body.id}/members`).set('Cookie', cookie);
    expect(members.status).toBe(200);
    expect((await write('post', `/role-subjects/sources/group/${group.body.id}/members/end`, { members: [{ id: members.body[0].id, version: members.body[0].version }] })).status).toBe(201);
    expect((await request(app.getHttpServer()).get(base + '/roles').set('Cookie', userCookie)).status).toBe(403);
    expect((await write('post', `/role-subjects/sources/group/${group.body.id}/members/end`, { members: [{ id: members.body[0].id, version: members.body[0].version }] })).status).toBe(409);
    expect((await write('post', `/role-subjects/sources/group/${group.body.id}/members`, { userIds: [userId], ...period, effectiveAt: new Date().toISOString() })).status).toBe(201);
    expect((await request(app.getHttpServer()).get(base + '/roles').set('Cookie', userCookie)).status).toBe(200);
    expect((await write('post', '/role-subjects/groups', { id: group.body.id, version: 1, groupCode: 'qa-' + suffix, groupName: '动态授权隔离组', status: 'DISABLED' })).status).toBe(201);
    expect((await request(app.getHttpServer()).get(base + '/roles').set('Cookie', userCookie)).status).toBe(403);
    expect((await write('post', '/role-subjects/groups', { id: group.body.id, version: 1, groupCode: 'qa-' + suffix, groupName: '过期写入', status: 'ACTIVE' })).status).toBe(409);
  });
  it('does not expose hidden or masked values through sorting and filters', async () => {
    const resource = await db.sysAuthorizationResource.findFirstOrThrow({ where: { bindingKey: 'customer', application: { applicationCode: 'demo-portal' } } });
    const current = (await request(app.getHttpServer()).get(base + `/role-policies/${roleId}/${resource.id}/read`).set('Cookie', cookie)).body;
    const published = await write('post', `/role-policies/${roleId}/${resource.id}/read`, { version: current.version, roleVersion: current.roleVersion, rules: current.rules, viewIds: current.viewIds, fields: [
      { field: 'industryValue', visible: false, writable: false, exportable: false, mask: 'NONE' },
      { field: 'customerName', visible: true, writable: false, exportable: false, mask: 'PARTIAL' },
    ] });
    expect(published.status).toBe(201);
    const userCookie = `ipl_session=${app.get(SessionSigner).issue(userId)}`;
    expect((await request(app.getHttpServer()).get(base + '/customers?industryValue=retail').set('Cookie', userCookie)).status).toBe(403);
    expect((await request(app.getHttpServer()).get(base + '/customers?orderBy=customerName').set('Cookie', userCookie)).status).toBe(403);
    expect((await request(app.getHttpServer()).get(base + '/customers').set('Cookie', userCookie)).status).toBe(200);
  });
  it('checks data-bearing role delegation when enabling through either API', async () => {
    const editor = await write('post', '/roles', { roleCode: 'editor-' + suffix, roleName: '角色编辑隔离测试' });
    expect(editor.status).toBe(201);
    const permissions = await db.sysPermission.findMany({ where: { application: { applicationCode: 'demo-portal' }, permissionCode: { in: ['access.role.update', 'access.role.status.manage'] } } });
    expect(permissions).toHaveLength(2);
    expect((await write('put', `/access/roles/${editor.body.id}/permissions`, { roleVersion: 1, permissionIds: permissions.map((p) => p.id) })).status).toBe(200);
    expect((await write('post', `/access/roles/${editor.body.id}/members/batch`, { action: 'add', userIds: [userId], effectiveAt: new Date(Date.now() - 1000).toISOString(), expiresAt: null })).status).toBe(201);
    const userCookie = `ipl_session=${app.get(SessionSigner).issue(userId)}; ipl_csrf=role015-test`;
    const role = await db.iamRole.findUniqueOrThrow({ where: { id: roleId } });
    expect((await write('patch', `/roles/${roleId}`, { version: role.version, isEnabled: true }, userCookie)).status).toBe(403);
    expect((await write('patch', `/access/roles/${roleId}/status`, { version: role.version, status: 'ACTIVE' }, userCookie)).status).toBe(403);
    expect((await db.iamRole.findUniqueOrThrow({ where: { id: roleId } })).version).toBe(role.version);
  });
});
