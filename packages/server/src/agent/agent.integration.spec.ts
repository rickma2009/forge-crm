import { Test } from '@nestjs/testing';
import type { INestApplication } from '@nestjs/common';
import cookieParser from 'cookie-parser';
import request from 'supertest';
import { randomUUID } from 'node:crypto';
import { AppModule } from '../app.module';
import { DatabaseService } from '../database/database.service';
import { ApiExceptionFilter } from '../http/api-exception.filter';
import { AiAnalysisService } from '../ai/ai-analysis.service';
import { AgentService } from './agent.service';
import { AgentProvider } from './agent-provider';
const run = process.env.RUN_AGENT_DB_TESTS === '1' ? describe : describe.skip;
run('Agent authenticated API and isolated database', () => {
  let app: INestApplication, db: DatabaseService, api: ReturnType<typeof request.agent>, csrf: string, id: string, user: string;
  const base = () => `/api/systems/demo-portal/opportunities/${id}/agent-tasks`;
  const post = (url: string, body: object = {}) => api.post(url).set('Origin', 'http://localhost:5173').set('X-CSRF-Token', csrf).send(body);
  beforeAll(async () => {
    if (!new URL(process.env.DATABASE_URL!).pathname.startsWith('/sdd_agent_')) throw new Error('ISOLATED_AGENT_TEST_DATABASE_REQUIRED');
    process.env.AI_PROVIDER = 'mock'; process.env.AI_MODEL = 'mock';
    app = (await Test.createTestingModule({ imports: [AppModule] }).compile()).createNestApplication();
    app.use(cookieParser()); app.useGlobalFilters(new ApiExceptionFilter()); await app.listen(0);
    app.get(AiAnalysisService).onModuleDestroy(); app.get(AgentService).onModuleDestroy(); db = app.get(DatabaseService); api = request.agent(app.getHttpServer());
    const session = await api.get('/api/auth/session'); csrf = (session.headers['set-cookie'] as unknown as string[]).map(c => c.match(/^ipl_csrf=([^;]+)/)?.[1]).find(Boolean)!;
    expect((await post('/api/auth/login', { account: 'admin', password: process.env.INITIAL_ADMIN_PASSWORD })).status).toBe(201);
    id = (await db.sdOpp.findFirstOrThrow({ where: { systemCode: 'demo-portal' } })).id; user = (await db.iamUser.findFirstOrThrow({ where: { account: 'admin' } })).id;
  }, 30000);
  afterAll(async () => { await app?.close(); });
  it('runs model-selected tools, restores tasks and saves a reviewed plan exactly once', async () => {
    const before = await db.sdOpp.findUniqueOrThrow({ where: { id } }); const count = await db.sdOppFollowUp.count({ where: { opportunityId: id } });
    const input = { requestId: randomUUID(), mode: 'COMMUNICATION_PLAN', instruction: '制定交期沟通计划' };
    const [a, b] = await Promise.all([post(base(), input), post(base(), input)]);
    expect(a.status).toBe(201); expect(b.status).toBe(201); expect(a.body.id).toBe(b.body.id);
    expect((await post(base(), { ...input, requestId: randomUUID() })).status).toBe(409);
    await app.get(AgentService).tick(); const draft = await api.get(`${base()}/${a.body.id}`);
    expect(draft.body.status).toBe('SUCCEEDED'); expect(draft.body.result.sections).toHaveLength(6);
    expect(draft.body.steps.filter((s: { kind: string; status: string }) => s.kind === 'TOOL' && s.status === 'SUCCEEDED')).toHaveLength(3);
    expect(await db.sdOppFollowUp.count({ where: { opportunityId: id } })).toBe(count); expect(draft.body.followUpId).toBeNull();
    const forged = structuredClone(draft.body.result); forged.sections[0].items[0].sourceIds = ['O:unread'];
    expect((await post(`${base()}/${a.body.id}/save-plan`, { result: forged, followedAt: new Date().toISOString(), workItem: '无效引用', resultNext: '拒绝保存' })).status).toBe(400);
    expect((await api.get(base())).body.items[0].id).toBe(a.body.id);
    const stranger = (await db.iamUser.findFirstOrThrow({ where: { account: { not: 'admin' }, status: 'ACTIVE' } })).id;
    await expect(app.get(AgentService).detail('demo-portal', id, a.body.id, stranger)).rejects.toThrow();
    expect((await api.get(`/api/systems/demo-portal/opportunities/${randomUUID()}/agent-tasks/${a.body.id}`)).status).toBe(404);
    await db.sdOppFollowUp.create({ data: { opportunityId: id, followedAt: new Date(), followerUserId: user, followerName: '测试', workItem: '需求变化', status: 'ACTIVE', createdBy: 'test', updatedBy: 'test' } });
    const plan = { result: draft.body.result, followedAt: new Date().toISOString(), workItem: '人工审阅的交期计划', resultNext: '联系客户确认交付时间' };
    expect((await post(`${base()}/${a.body.id}/save-plan`, plan)).status).toBe(409);
    const [c, d] = await Promise.all([post(`${base()}/${a.body.id}/save-plan`, { ...plan, acceptStale: true }), post(`${base()}/${a.body.id}/save-plan`, { ...plan, acceptStale: true })]);
    expect(c.status).toBe(201); expect(d.status).toBe(201); expect(c.body.followUpId).toBe(d.body.followUpId);
    const saved = await db.sdOppFollowUp.findUniqueOrThrow({ where: { id: c.body.followUpId } });
    expect(saved.workItem).toBe('[Agent沟通计划·待执行] 人工审阅的交期计划'); expect(saved.resultNext).toBe(plan.resultNext);
    expect(await db.sdOppFollowUp.count({ where: { opportunityId: id } })).toBe(count + 2);
    const after = await db.sdOpp.findUniqueOrThrow({ where: { id } });
    expect([after.stageId, after.stageProbability, after.confidence, after.version]).toEqual([before.stageId, before.stageProbability, before.confidence, before.version]);
  });
  it('cancels queued/running work and reports interrupted jobs', async () => {
    const queued = await post(base(), { requestId: randomUUID(), mode: 'FOLLOW_UP' }); expect(queued.status).toBe(201);
    expect((await post(`${base()}/${queued.body.id}/cancel`)).body.status).toBe('CANCELLED'); await app.get(AgentService).tick();
    expect((await api.get(`${base()}/${queued.body.id}`)).body.result).toBeNull();
    const running = await post(base(), { requestId: randomUUID(), mode: 'FOLLOW_UP' });
    const provider = app.get(AgentProvider), original = provider.turn.bind(provider); let entered!: () => void, release!: () => void;
    const started = new Promise<void>(r => { entered = r; }), gate = new Promise<void>(r => { release = r; });
    const spy = jest.spyOn(provider, 'turn').mockImplementationOnce(async (...args) => { entered(); await gate; return original(...args); });
    const tick = app.get(AgentService).tick(); await started; expect((await post(`${base()}/${running.body.id}/cancel`)).body.status).toBe('CANCELLED'); release(); await tick; spy.mockRestore();
    expect((await api.get(`${base()}/${running.body.id}`)).body.result).toBeNull();
    const interrupted = await post(base(), { requestId: randomUUID(), mode: 'FOLLOW_UP' });
    await db.agentTask.update({ where: { id: interrupted.body.id }, data: { status: 'RUNNING', startedAt: new Date(Date.now() - 10 * 60000) } }); await app.get(AgentService).tick();
    expect((await api.get(`${base()}/${interrupted.body.id}`)).body.status).toBe('FAILED');
  });
  it('rejects missing CSRF and revoked AI permission', async () => {
    expect((await api.post(base()).set('Origin', 'http://localhost:5173').send({ requestId: randomUUID(), mode: 'FOLLOW_UP' })).status).toBe(403);
    const permission = await db.sysPermission.findFirstOrThrow({ where: { permissionCode: 'menu.opportunity-directory.ai-analyze' } });
    await db.iamRolePermission.updateMany({ where: { permissionId: permission.id }, data: { status: 'DISABLED' } });
    expect((await post(base(), { requestId: randomUUID(), mode: 'FOLLOW_UP' })).status).toBe(403);
  });
});
